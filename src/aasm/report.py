"""Quality note along the ESS dimensions, written to docs/quality.md."""
from __future__ import annotations

import csv
import json
from datetime import date
from pathlib import Path

from aasm.curated import Rows, load_all

STALE_DAYS = 90
PERIMETER = "Articles 8–15"


def quality_note(tables: dict[str, Rows], lineage: dict | None, coverage: list[dict], history: list[dict],
                 state: dict, today: date) -> str:
    req, dlv, std = tables["requirements"], tables["request_deliverables"], tables["standards"]
    covered = sum(1 for c in coverage if c["status"] != "uncovered")
    noted = sum(1 for s in std if s["note"].strip())
    judged = sum(1 for s in std if "judgement" in s["note"].lower())  # judgements say so in their note
    first_seen = len({h["wi_ref"] for h in history})
    retrieved = [date.fromisoformat(s["retrieved_at"]) for s in std if s["retrieved_at"]]
    latest = max(retrieved).isoformat() if retrieved else "none"
    stale = sum(1 for d in retrieved if (today - d).days > STALE_DAYS)
    with_wi = {s["deliverable_id"] for s in std}
    no_wi = [d["deliverable_id"] for d in dlv if d["deliverable_id"] not in with_wi]
    covered_reqs = {r for d in dlv for r in d["covers_req_ids"].split("|") if r}
    no_dlv = [r["req_id"] for r in req if r["req_id"] not in covered_reqs]
    eurostat = (f"{lineage['rows']} rows retrieved {lineage['retrieved_at']}, Eurostat last update "
                f"{lineage.get('eurostat_updated')}") if lineage else "Eurostat: not fetched"
    lines = [
        f"# Quality note ({today.isoformat()})",
        "",
        "Generated by `aasm report`. Dimensions follow the European Statistical System quality framework.",
        "",
        "## Relevance",
        f"- Perimeter: high-risk AI systems, {PERIMETER} of Regulation (EU) 2024/1689; "
        f"{len(req)} requirements, {len(dlv)} deliverables of standardisation request M/593, "
        f"{len(std)} work items.",
        f"- {covered} of {len(req)} requirements are covered by at least one work item "
        f"at {today.isoformat()}.",
        "",
        "## Accuracy",
        f"- Work-item rows whose link to a deliverable is a judgement: {judged} of {len(std)}; "
        f"rows with other caveats: {noted - judged}. Each note says which.",
        "- Every row has a public `source_url`; no standard text is reproduced. "
        "The project describes, it does not interpret.",
        "",
        "## Timeliness",
        f"- Latest `retrieved_at` on work items: {latest}; rows older than {STALE_DAYS} days: {stale}.",
        f"- Pages watched weekly: {len(std)}; stage changes observed: {len(history) - first_seen}; "
        f"first observations: {first_seen}.",
        f"- Adoption data: {eurostat}.",
        "",
        "## Coherence",
        f"- Deliverables without a public work item: {', '.join(no_wi) if no_wi else 'none'}.",
        f"- Requirements not covered by any deliverable: {', '.join(no_dlv) if no_dlv else 'none'}.",
        "",
        "## Accessibility",
        "- Tables: `data/curated/`, `data/fetched/`, `data/derived/` (CSV, UTF-8). "
        "Licence: CC BY 4.0 (`data/LICENSE`).",
        "- Method: `docs/methodology.md`. Results: `docs/results.md`.",
        "",
    ]
    return "\n".join(lines)


def _read_csv(path: Path) -> list[dict]:
    return list(csv.DictReader(path.open(encoding="utf-8", newline=""))) if path.exists() else []


def write(root: Path, today: date) -> Path:
    tables = load_all(root / "data" / "curated")
    lin_path = root / "data" / "fetched" / "lineage.json"
    lineage = json.loads(lin_path.read_text()) if lin_path.exists() else None
    coverage = _read_csv(root / "data" / "derived" / "coverage_by_requirement.csv")
    history = _read_csv(root / "data" / "derived" / "standards_history.csv")
    state_path = root / "data" / "watch_state.json"
    state = json.loads(state_path.read_text()) if state_path.exists() else {}
    out = root / "docs" / "quality.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(quality_note(tables, lineage, coverage, history, state, today), encoding="utf-8")
    return out
